import { mainMenu } from '../keyboards/main.js';

export function registerCommands(bot) {
    bot.start((ctx) => {
        ctx.reply(
            `Привет, ${ctx.from.first_name}! 👋\n\n` +
                'Я помогу тебе решить, что приготовить сегодня.\n\n' +
                'Выбери действие:',
            mainMenu(),
        );
    });

    bot.help((ctx) => {
        ctx.reply(
            '📖 Управление рецептами:\n\n' +
                '• ➕ Добавить рецепт — выбрать категорию и ввести название\n' +
                '• 📋 Все рецепты — показать список всех рецептов\n' +
                '• 🍳/🥗/🍲 — просмотр рецептов по категориям\n' +
                '• 🗑 Удалить рецепт — выбрать рецепт для удаления',
        );
    });
}
